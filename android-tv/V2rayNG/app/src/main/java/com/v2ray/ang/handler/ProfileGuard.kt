package com.v2ray.ang.handler

import com.v2ray.ang.core.CoreServiceManager

/**
 * Занят ли профиль прямо сейчас, то есть нельзя ли его удалять.
 *
 * Исходный проект запрещал удалять выбранный профиль всегда, а выбранным
 * он остаётся и после отключения VPN — поэтому удалить его было нельзя
 * вообще никогда, пока не переключишься на другой, и человек получал
 * «Это действие запрещено» без единого намёка на причину.
 *
 * На деле опасен только один случай: на этом профиле прямо сейчас поднято
 * соединение. Выбор при удалении сбрасывает само хранилище
 * (см. [MmkvManager.removeServer]), так что в остальном удалять безопасно.
 */
fun isProfileInUse(guid: String): Boolean =
    guid.isNotEmpty() &&
        guid == MmkvManager.getSelectServer() &&
        CoreServiceManager.isRunning() == true
